// ============================================================================
//  PHANTOM NET — ml_fall.cpp
//
//  Keeps a rolling 1-second (200-sample) window of the IMU stream, computes
//  the exact same 37 features train_fall.py computed, and scores it with
//  the Random Forest exported to fall_model.h.
//
//  REQUIRES fall_model.h in this same folder - copy it from
//  ML\dataset\_training\fall_model.h (the file train_fall.py wrote).
//
//  WHY THE FEATURE CODE BELOW MUST MATCH train_fall.py EXACTLY
//  -------------------------------------------------------------
//  The model was trained on numbers computed one specific way (mean, std,
//  min/max, a jerk value, a tilt angle...). If this file computes those
//  numbers even slightly differently, the model is being fed data that
//  doesn't look like anything it was trained on, and its output becomes
//  meaningless - not obviously wrong, just quietly wrong. Every step below
//  mirrors extract() in train_fall.py line for line.
// ============================================================================

#include "ml_fall.h"
#include "config.h"
#include "fall_model.h"     // AUTO-GENERATED by train_fall.py - do not edit
#include <math.h>

#ifndef M_PI
#define M_PI 3.14159265358979323846f
#endif

#if ML_N_FEATURES != 37
#error "fall_model.h feature count changed - extract() below must be updated to match"
#endif

// ---------------------------------------------------------------------------
//  ROLLING WINDOW - same 200 samples / 1 second the model was trained on
// ---------------------------------------------------------------------------
#define ML_WIN   200     // FS * WIN_SEC in train_fall.py  (200 Hz * 1.0 s)
#define ML_STEP  50      // WIN/4 - same 75% overlap stride train_fall.py used

static float    s_ax[ML_WIN], s_ay[ML_WIN], s_az[ML_WIN];
static float    s_gx[ML_WIN], s_gy[ML_WIN], s_gz[ML_WIN];
static float    s_amag[ML_WIN];
static uint16_t s_head      = 0;   // oldest sample currently lives here
static uint16_t s_count     = 0;   // samples written so far, caps at ML_WIN
static uint16_t s_sinceEval = 0;

static bool  s_ready = false;
static float s_prob  = 0.0f;

// ---------------------------------------------------------------------------
void ml_fall_begin() {
  s_head = s_count = s_sinceEval = 0;
  s_ready = false;
  s_prob  = 0.0f;
}

bool  ml_fall_ready() { return s_ready; }
float ml_fall_score() { return s_prob;  }

// ---------------------------------------------------------------------------
//  mean, std, min, max, range, rms - the same six numbers train_fall.py's
//  _stats() computes, in the same order.
// ---------------------------------------------------------------------------
static void stats6(const float* v, int n, float* mean, float* std_,
                    float* mn, float* mx, float* rng, float* rms) {
  float sum = 0, sumSq = 0;
  *mn = v[0]; *mx = v[0];
  for (int i = 0; i < n; i++) {
    sum   += v[i];
    sumSq += v[i] * v[i];
    if (v[i] < *mn) *mn = v[i];
    if (v[i] > *mx) *mx = v[i];
  }
  *mean = sum / n;
  float varSum = 0;
  for (int i = 0; i < n; i++) {
    const float d = v[i] - *mean;
    varSum += d * d;
  }
  *std_ = sqrtf(varSum / n);
  *rng  = *mx - *mn;
  *rms  = sqrtf(sumSq / n);
}

// ---------------------------------------------------------------------------
//  extract() - builds f[0..36] in EXACTLY the order train_fall.py's
//  extract() built them. See the "f[N] = name" comment block at the top of
//  fall_model.h if you ever need to double check the order.
// ---------------------------------------------------------------------------
static void extract(const float* ax, const float* ay, const float* az,
                     const float* gx, const float* gy, const float* gz,
                     const float* amag, int n, float* f) {
  static float gmag[ML_WIN];
  for (int i = 0; i < n; i++)
    gmag[i] = sqrtf(gx[i]*gx[i] + gy[i]*gy[i] + gz[i]*gz[i]);

  int k = 0;
  float mean, std_, mn, mx, rng, rms;

  stats6(amag, n, &mean, &std_, &mn, &mx, &rng, &rms);
  f[k++] = mean; f[k++] = std_; f[k++] = mn; f[k++] = mx; f[k++] = rng; f[k++] = rms;
  const float amag_min = mn, amag_max = mx;

  stats6(gmag, n, &mean, &std_, &mn, &mx, &rng, &rms);
  f[k++] = mean; f[k++] = std_; f[k++] = mn; f[k++] = mx; f[k++] = rng; f[k++] = rms;

  stats6(ax, n, &mean, &std_, &mn, &mx, &rng, &rms);
  f[k++] = mean; f[k++] = std_; f[k++] = mn; f[k++] = mx; f[k++] = rng; f[k++] = rms;

  stats6(ay, n, &mean, &std_, &mn, &mx, &rng, &rms);
  f[k++] = mean; f[k++] = std_; f[k++] = mn; f[k++] = mx; f[k++] = rng; f[k++] = rms;

  stats6(az, n, &mean, &std_, &mn, &mx, &rng, &rms);
  f[k++] = mean; f[k++] = std_; f[k++] = mn; f[k++] = mx; f[k++] = rng; f[k++] = rms;

  // --- fall-specific features - must match train_fall.py's extract() ---
  int below05 = 0, above25 = 0;
  for (int i = 0; i < n; i++) {
    if (amag[i] < 0.5f) below05++;
    if (amag[i] > 2.5f) above25++;
  }
  f[k++] = (float)below05 / n;           // amag_below05
  f[k++] = (float)above25 / n;           // amag_above25
  f[k++] = amag_max;                     // amag_peak
  f[k++] = amag_min;                     // amag_trough
  f[k++] = amag_max - amag_min;          // amag_swing

  float jerkMax = 0;
  for (int i = 1; i < n; i++) {
    const float d = fabsf(amag[i] - amag[i - 1]);
    if (d > jerkMax) jerkMax = d;
  }
  f[k++] = jerkMax;                      // jerk_max

  // tilt_deg: gravity direction, first 10% of the window vs the last 10%
  const int edge = n / 10;               // matches FS//10 in train_fall.py
  float g0x = 0, g0y = 0, g0z = 0, g1x = 0, g1y = 0, g1z = 0;
  for (int i = 0; i < edge; i++)        { g0x += ax[i]; g0y += ay[i]; g0z += az[i]; }
  for (int i = n - edge; i < n; i++)    { g1x += ax[i]; g1y += ay[i]; g1z += az[i]; }
  g0x /= edge; g0y /= edge; g0z /= edge;
  g1x /= edge; g1y /= edge; g1z /= edge;
  const float n0 = sqrtf(g0x*g0x + g0y*g0y + g0z*g0z);
  const float n1 = sqrtf(g1x*g1x + g1y*g1y + g1z*g1z);
  float tilt = 0.0f;
  if (n0 > 0.1f && n1 > 0.1f) {
    float dot = (g0x*g1x + g0y*g1y + g0z*g1z) / (n0 * n1);
    if (dot >  1.0f) dot =  1.0f;
    if (dot < -1.0f) dot = -1.0f;
    tilt = acosf(dot) * 180.0f / (float)M_PI;
  }
  f[k++] = tilt;                         // tilt_deg
  // k is now 37 - if this ever mismatches ML_N_FEATURES, the #if above
  // will refuse to compile rather than silently feed the model garbage.
}

// ---------------------------------------------------------------------------
void ml_fall_update() {
  // push the newest sample into the circular buffer
  s_ax[s_head] = g_node.ax; s_ay[s_head] = g_node.ay; s_az[s_head] = g_node.az;
  s_gx[s_head] = g_node.gx; s_gy[s_head] = g_node.gy; s_gz[s_head] = g_node.gz;
  s_amag[s_head] = g_node.amag;
  s_head = (s_head + 1) % ML_WIN;
  if (s_count < ML_WIN) s_count++;
  s_sinceEval++;

  if (s_count < ML_WIN) return;          // buffer not full yet (~first 1 s)
  if (s_sinceEval < ML_STEP) return;     // wait for the next 250 ms stride
  s_sinceEval = 0;

  // unwrap the circular buffer into time order (oldest -> newest) - jerk_max
  // and tilt_deg both depend on the samples being in the right sequence.
  static float wax[ML_WIN], way[ML_WIN], waz[ML_WIN];
  static float wgx[ML_WIN], wgy[ML_WIN], wgz[ML_WIN], wamag[ML_WIN];
  for (int i = 0; i < ML_WIN; i++) {
    const int j = (s_head + i) % ML_WIN;   // s_head currently points at the oldest slot
    wax[i] = s_ax[j]; way[i] = s_ay[j]; waz[i] = s_az[j];
    wgx[i] = s_gx[j]; wgy[i] = s_gy[j]; wgz[i] = s_gz[j];
    wamag[i] = s_amag[j];
  }

  float f[ML_N_FEATURES];
  extract(wax, way, waz, wgx, wgy, wgz, wamag, ML_WIN, f);

  s_prob  = ml_fall_probability(f);   // from fall_model.h - averages all trees
  s_ready = true;
}
